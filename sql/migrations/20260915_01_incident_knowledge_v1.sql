CREATE TABLE DH_INCIDENTS (
  INCIDENT_ID            VARCHAR2(32)   NOT NULL,
  FINGERPRINT            VARCHAR2(128)  NOT NULL,
  ENV                    VARCHAR2(32)   DEFAULT 'unknown' NOT NULL,
  LAYER                  VARCHAR2(32)   NOT NULL,
  SEVERITY               VARCHAR2(8)    NOT NULL,
  BLAST_RADIUS           VARCHAR2(32)   DEFAULT 'ONE REQUEST' NOT NULL,
  SYMPTOM                VARCHAR2(4000),
  ROOT_CAUSE             VARCHAR2(4000),
  SOLUTION               VARCHAR2(4000),
  FIX_TYPE               VARCHAR2(32),
  STATUS                 VARCHAR2(32)   DEFAULT 'OPEN' NOT NULL,
  OCCURRENCE_COUNT       NUMBER         DEFAULT 0 NOT NULL,
  FIRST_SEEN_AT          TIMESTAMP WITH TIME ZONE,
  LAST_SEEN_AT           TIMESTAMP WITH TIME ZONE,
  RESOLVED_AT            TIMESTAMP WITH TIME ZONE,
  DIAGNOSIS_DURATION_MS  NUMBER,
  REPAIR_DURATION_MS     NUMBER,
  TOTAL_DURATION_MS      NUMBER,
  DIAGNOSED_BY           VARCHAR2(100),
  RECOMMENDED_BY         VARCHAR2(100),
  IMPLEMENTED_BY         VARCHAR2(100),
  VERIFIED_BY            VARCHAR2(100),
  QA_RESULT              VARCHAR2(32),
  GIT_SHA                VARCHAR2(64),
  GIT_BRANCH             VARCHAR2(128),
  FILES_REF              VARCHAR2(4000),
  DB_OBJECT_REF          VARCHAR2(500),
  CONFIG_REF             VARCHAR2(500),
  NETWORK_REF            VARCHAR2(500),
  ROLLBACK_REF           VARCHAR2(500),
  RUNBOOK_REF            VARCHAR2(500),
  BEFORE_EVIDENCE_REF    VARCHAR2(500),
  AFTER_EVIDENCE_REF     VARCHAR2(500),
  CONFIDENCE             NUMBER(5,2),
  AUTO_REPAIR_FORBIDDEN  CHAR(1)        DEFAULT 'Y' NOT NULL,
  CREATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT             TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_DH_INCIDENTS PRIMARY KEY (INCIDENT_ID),
  CONSTRAINT UQ_DH_INCIDENTS_FP UNIQUE (FINGERPRINT),
  CONSTRAINT CK_DH_INC_SEV CHECK (SEVERITY IN ('SEV-1','SEV-2','SEV-3','SEV-4')),
  CONSTRAINT CK_DH_INC_STATUS CHECK (STATUS IN ('OPEN','INVESTIGATING','RESOLVED','REGRESSION')),
  CONSTRAINT CK_DH_INC_FIX CHECK (FIX_TYPE IS NULL OR FIX_TYPE IN ('CODE','DATABASE','CONFIG','NETWORK','DEPLOYMENT')),
  CONSTRAINT CK_DH_INC_BLAST CHECK (BLAST_RADIUS IN (
    'ONE REQUEST','ROUTE','TENANT','MULTIPLE TENANTS','PLATFORM-WIDE'
  )),
  CONSTRAINT CK_DH_INC_LAYER CHECK (LAYER IN ('APP','ORACLE','NETWORK','CONFIG','DEPLOY','BUILD')),
  CONSTRAINT CK_DH_INC_AUTOREPAIR CHECK (AUTO_REPAIR_FORBIDDEN = 'Y')
);

CREATE TABLE DH_INCIDENT_OCCURRENCES (
  OCCURRENCE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  INCIDENT_ID            VARCHAR2(32) NOT NULL,
  SEEN_AT                TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ENV                    VARCHAR2(32),
  LAYER                  VARCHAR2(32),
  SANITIZED_SUMMARY      VARCHAR2(4000) NOT NULL,
  HOST_HASH              VARCHAR2(64),
  REQUEST_PATH           VARCHAR2(500),
  NOTES                  VARCHAR2(1000),
  CONSTRAINT FK_DH_OCC_INC FOREIGN KEY (INCIDENT_ID) REFERENCES DH_INCIDENTS (INCIDENT_ID)
);

CREATE INDEX IX_DH_OCC_INC_SEEN ON DH_INCIDENT_OCCURRENCES (INCIDENT_ID, SEEN_AT);

COMMENT ON TABLE DH_INCIDENTS IS 'Reliability V1 incident knowledge - diagnosis memory only; never auto-repair.';
COMMENT ON COLUMN DH_INCIDENTS.FILES_REF IS 'JSON array of file paths / commit refs - never full source dumps.';
COMMENT ON COLUMN DH_INCIDENTS.AUTO_REPAIR_FORBIDDEN IS 'Always Y - historical patch is not execution authority.';

-- Seed known catalog rows (no invented occurrence timestamps/durations)
MERGE INTO DH_INCIDENTS t
USING (
  SELECT 'INC-001' INCIDENT_ID, 'NJS-040' FINGERPRINT FROM DUAL UNION ALL
  SELECT 'INC-002', 'ORA-20004' FROM DUAL UNION ALL
  SELECT 'INC-003', 'ORA-20501' FROM DUAL UNION ALL
  SELECT 'INC-004', 'NPM-ERESOLVE' FROM DUAL
) s ON (t.INCIDENT_ID = s.INCIDENT_ID)
WHEN NOT MATCHED THEN INSERT (
  INCIDENT_ID, FINGERPRINT, ENV, LAYER, SEVERITY, BLAST_RADIUS, STATUS,
  OCCURRENCE_COUNT, SYMPTOM, ROOT_CAUSE, SOLUTION, FIX_TYPE, RUNBOOK_REF,
  AUTO_REPAIR_FORBIDDEN, CONFIDENCE
) VALUES (
  s.INCIDENT_ID, s.FINGERPRINT, 'production', 
  CASE s.INCIDENT_ID WHEN 'INC-004' THEN 'BUILD' WHEN 'INC-001' THEN 'ORACLE' WHEN 'INC-002' THEN 'ORACLE' ELSE 'ORACLE' END,
  CASE s.INCIDENT_ID WHEN 'INC-002' THEN 'SEV-2' WHEN 'INC-001' THEN 'SEV-1' WHEN 'INC-003' THEN 'SEV-2' ELSE 'SEV-3' END,
  CASE s.INCIDENT_ID WHEN 'INC-002' THEN 'TENANT' WHEN 'INC-001' THEN 'PLATFORM-WIDE' WHEN 'INC-003' THEN 'ROUTE' ELSE 'ONE REQUEST' END,
  'OPEN', 0,
  'See lib/incidents/catalog.ts',
  'See lib/incidents/catalog.ts',
  'See lib/incidents/catalog.ts + runbook',
  CASE s.INCIDENT_ID WHEN 'INC-004' THEN 'CONFIG' WHEN 'INC-002' THEN 'DATABASE' ELSE 'CONFIG' END,
  'docs/runbooks/' || s.INCIDENT_ID || '.md',
  'Y', 0.90
);
